-- Description: Oracle Table for Admin & Student Authentication (Sign In, Sign Up, Forgot Password)
-- ====================================================================

SET DEFINE OFF;

BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE SYSTEM_USERS CASCADE CONSTRAINTS PURGE';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE SYSTEM_USERS (
    USER_ID       NUMBER(10)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FULL_NAME     VARCHAR2(100)  NOT NULL,
    EMAIL         VARCHAR2(100)  NOT NULL UNIQUE,
    PASSWORD      VARCHAR2(100)  NOT NULL,
    ROLE          VARCHAR2(20)   NOT NULL CHECK (ROLE IN ('ADMIN', 'STUDENT')),
    STUDENT_REF   NUMBER(10)     NULL,
    DEPARTMENT    VARCHAR2(100)  NOT NULL
);

